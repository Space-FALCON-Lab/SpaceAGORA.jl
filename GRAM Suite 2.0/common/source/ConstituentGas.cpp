//! \brief Compute the specific heat capacities, Cp and Cv, at a given temperature and pressure.
//!
//! The specific heat capacities, Cp and Cv, are computed for the specified gas, 
//! temperature, and pressure using lookup tables and linear interpolation.
//! \param type The gas type.
//! \param temperature The temperature (K) of the gas.
//! \param pressure The pressure (Pa) of the gas.
//! \returns specificHeatPressure and specificHeatVolume (J/mol K).
void ConstituentGas::updateSpecificHeatCapacity(GasType type, greal temperature, greal pressure)
{
  // Try to update using 1D data.  If this is not 1D data, then update using 2D data.
  if (update1D(type, temperature) == false) {
    update2D(type, temperature, pressure);
  }

  // Four special cases for pressures below 1.0
  if (pressure < 1.0) {
    if (type == DIOXYGEN) {
      updateO2(type, temperature, pressure);
    }
    else if (type == WATER) {
      updateH2O(type, temperature, pressure);
    }
  }
}

//! \brief Performs table lookups on gases that vary only by temperature.
//!
//! The specific heat capacities, Cp and Cv, are computed for the specified gas and 
//! temperature using lookup tables and linear interpolation.
//! \param type The gas type.
//! \param temperature The temperature (K) of the gas.
//! \returns specificHeatPressure and specificHeatVolume (J/mol K).
bool ConstituentGas::update1D(GasType type, greal temperature)
{
  // Get the <GasType, T_Array> pair of cp data for this type
  auto cpPair = cpDataByT.find(type);

  // If not found, then this type is not 1D data.
  if (cpPair == cpDataByT.end()) {
    return false;
  }

  // If we found the cp pair, then the cv pair will exist too.
  auto cvPair = cvDataByT.find(type);

  // Get the data arrays.  They are the second elements of the pairs.
  T_Array &cpData = cpPair->second;
  T_Array &cvData = cvPair->second;

  // We use constant extrapolation. So we can bound temperature within the levels.
  greal temp = clamp(temperature, tLevel[0], tLevel[tSize - 1]);

  // Find the index of the lower bound.
  size_t index = getTemperatureIndex(temp);

  // Create an interpolator based on temperature.
  Interpolator interp;
  interp.makeFraction(tLevel[index], tLevel[index + 1], temp);

  // Use linear interpolation for cp and cv.
  specificHeatPressure = interp.linear(cpData[index], cpData[index + 1]);
  specificHeatVolume = interp.linear(cvData[index], cvData[index + 1]);

  // This gas type uses 1D data.
  return true;
}

//! \brief Performs table lookups on gases that vary by temperature and pressure.
//!
//! The specific heat capacities, Cp and Cv, are computed for the specified gas,  
//! temperature, and pressure using lookup tables and linear interpolation.
//! \param type The gas type.
//! \param temperature The temperature (K) of the gas.
//! \param pressure The pressure (Pa) of the gas.
//! \returns specificHeatPressure and specificHeatVolume (J/mol K).
void ConstituentGas::update2D(GasType type, greal temperature, greal pressure)
{
  // Get the <GasType, T_Array> pairs for this type
  auto cpPair = cpDataByTP.find(type);
  auto cvPair = cvDataByTP.find(type);

  // Get the data arrays.  They are the second elements of the pairs.
  TP_Array &cpData = cpPair->second;
  TP_Array &cvData = cvPair->second;

  // We use constant extrapolation. So we can bound within the levels.
  greal temp = clamp(temperature, tLevel[0], tLevel[tSize - 1]);
  greal pres = clamp(pressure, pLevel[0], pLevel[pSize - 1]);

  // Find the indices of the lower bounds.
  size_t tIndex = getTemperatureIndex(temp);
  size_t pIndex = getPressureIndex(pres);

  // Create an interpolator based on temperature and pressure.
  greal tFraction = (temp - tLevel[tIndex]) / (tLevel[tIndex + 1] - tLevel[tIndex]);
  greal pFraction = (pres - pLevel[pIndex]) / (pLevel[pIndex + 1] - pLevel[pIndex]);
  Interpolator interp(tFraction, pFraction);

  // Use linear interpolation for cp and cv.
  specificHeatPressure = interp.linear(cpData[tIndex][pIndex], cpData[tIndex][pIndex + 1],
    cpData[tIndex + 1][pIndex], cpData[tIndex + 1][pIndex + 1]);
  specificHeatVolume = interp.linear(cvData[tIndex][pIndex], cvData[tIndex][pIndex + 1],
    cvData[tIndex + 1][pIndex], cvData[tIndex + 1][pIndex + 1]);
}

//! \brief Special handling for some low pressure O2 cases.
//!
//! The specific heat capacities, Cp and Cv, are computed for the specified gas,  
//! temperature, and pressure using lookup tables and linear interpolation.
//! \param type The gas type.
//! \param temperature The temperature (K) of the gas.
//! \param pressure The pressure (Pa) of the gas.
//! \returns specificHeatPressure and specificHeatVolume (J/mol K).
void ConstituentGas::updateO2(GasType type, greal temperature, greal pressure)
{
  // This O2 data is for pressure levels 1.0e-7 and 1.0e-6
  // And for temperature levels 40, 50, 100
  static const greal cp[3][2] = {
    {0.9106,	0.9094},
    {0.9103,	0.9094},
    {0.9099,	0.9099}
  };
  static const greal cv[3][2] = {
    {0.6508,	0.6496},
    {0.6505,	0.6496},
    {0.6500,	0.6500}
  };

  // Get the temperature index
  size_t tIndex = getTemperatureIndex(temperature);

  // Only consider pressures below 1.0e-6 in the 40 - 100 temperature range
  if (pressure < 1.0e-6 && tIndex < 2) {

    // We use constant extrapolation. So we can bound within the levels.
    temperature = clamp(temperature, 40.0, 100.0);
    pressure = clamp(pressure, 1.0e-7, 1.0e-6);

    // Create the interpolator over temperature and pressure
    greal tFactor = (temperature - tLevel[tIndex]) / (tLevel[tIndex + 1] - tLevel[tIndex]);
    greal pFactor = (pressure - 1.0e-7) / (1.0e-6 - 1.0e-7);
    Interpolator interp(tFactor, pFactor);

    // Use linear interpolation for cp and cv.
    specificHeatPressure = interp.linear(cp[tIndex][0], cp[tIndex][1],
      cp[tIndex + 1][0], cp[tIndex + 1][1]);
    specificHeatVolume = interp.linear(cv[tIndex][0], cv[tIndex][1],
      cv[tIndex + 1][0], cv[tIndex + 1][1]);
  }
}

//! \brief Special handling for some low pressure H2O cases.
//!
//! The specific heat capacities, Cp and Cv, are computed for the specified gas,  
//! temperature, and pressure using lookup tables and linear interpolation.
//! \param type The gas type.
//! \param temperature The temperature (K) of the gas.
//! \param pressure The pressure (Pa) of the gas.
//! \returns specificHeatPressure and specificHeatVolume (J/mol K).
void ConstituentGas::updateH2O(GasType type, greal temperature, greal pressure)
{
  // This H2O data is for pressure levels 1.0e-7 and 1.0e-6
  // And for temperature levels 100, 150, 200, 250, 300
  static const greal cp[5][2] = {
    {1.8484,  1.8484},
    {1.8497,  1.8484},
    {1.8512,  1.8511},
    {1.8554,  1.8511},
    {1.8648,  1.8648}
  };
  static const greal cv[5][2] = {
    {1.3869,	1.3869},
    {1.3882,  1.3869},
    {1.3897,  1.3896},
    {1.3939,  1.3896},
    {1.4033,  1.4033}
  };

  // Get the temperature index
  size_t tIndex = getTemperatureIndex(temperature);

  // Only consider pressures below 1.0e-6 in the 100 - 300 temperature range
  if (pressure < 1.0e-6 && tIndex > 1 && tIndex < 7) {

    // We use constant extrapolation. So we can bound within the levels.
    pressure = clamp(pressure, 1.0e-7, 1.0e-6);

    // Create the interpolator over temperature and pressure
    greal tFactor = (temperature - 50.0 * tIndex) / 50.0;
    greal pFactor = (pressure - 1.0e-7) / (1.0e-6 - 1.0e-7);
    Interpolator interp(tFactor, pFactor);

    // Shift the temperature index to use the little tables above
    tIndex -= 2;

    // Use linear interpolation for cp and cv.
    specificHeatPressure = interp.linear(cp[tIndex][0], cp[tIndex][1],
      cp[tIndex + 1][0], cp[tIndex + 1][1]);
    specificHeatVolume = interp.linear(cv[tIndex][0], cv[tIndex][1],
      cv[tIndex + 1][0], cv[tIndex + 1][1]);
  }
}

//! \brief Find the lookup index of a temperature.
//!
//! The lower bound index of the temperature lookup table is computed.
//! \param temperature The temperature (K) of the gas.
//! \returns The lookup index (lower bound).
size_t ConstituentGas::getTemperatureIndex(greal temperature)
{
  greal tx = clamp(temperature, tLevel[0], tLevel[tSize - 2]);
  size_t index = size_t(tx / 50.0);
  return index;
}

//! \brief Find the lookup index of a pressure.
//!
//! The lower bound index of the pressure lookup table is computed.
//! \param pressure The pressure (Pa) of the gas.
//! \returns The lookup index (lower bound).
size_t ConstituentGas::getPressureIndex(greal pressure)
{
  greal px = clamp(pressure, pLevel[0], pLevel[pSize - 2]);
  size_t index = size_t(log10(px) + 2.1);
  return index;
}

