module ExtensionHooks

# The extension hook registry: one row per exported extension hook. `docs/make.jl`
# renders it into the Extension Hook Reference page, and
# `test/gates/ci_extension_hook_reference_gate.jl` checks it against the package
# and the docs tree. A pull request that adds, renames or deprecates a hook
# updates its row here.
#
# Row fields:
# - `symbol`: the root name, exported from `SpaceAGORA` and listed in
#   `docs/public_api_symbols.jl`.
# - `shape`: T tick, R right-hand side, Q query, D declaration, A accessor,
#   H hardware, P planner or algorithm, L configuration.
# - `signature`: exactly the first line of the docstring's signature block.
# - `called`: when the engine calls the hook.
# - `arguments`: the arguments and results, with units where they are not obvious.
# - `fallback`: `none` (every type needs its own method), `returns ...` or
#   `throws ...`; the gate compares it with the method table at each documented
#   arity. What the fallback returns is for the hook's own tests.
# - `base`: the type a model that implements the hook subtypes. A method counts
#   as the hook's fallback only when its dispatch argument is untyped or typed
#   with `base` or a supertype of it, so that every such model reaches it. Each
#   group sets a `base`; a row sets its own only where it differs. `:Any` where
#   the hook has no such type.
# - `status`: `current` or `deprecated`, which must agree with the docstring: a
#   row is deprecated exactly when its docstring opens with "Deprecated". A
#   deprecated row names its `replacement` (itself a row) and `removed_in`, which
#   is `REMOVAL_RELEASE`.
# - `page`: the page under `docs/src` that explains the hook, or `nothing`
#   while none does (then a `KNOWN_GAPS` entry says so).

export HOOK_SECTIONS, EXTENSION_HOOK_GROUPS, NOT_HOOKS, KNOWN_GAPS, VERSIONED_FACADES,
    REMOVAL_RELEASE, extension_hook_rows

